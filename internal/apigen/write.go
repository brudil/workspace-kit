// name gives each found type its name in the app: its Go name. Where two
// packages' types share one, the types of each (but the plugin's main,
// whose names are left alone) get their package's name in front:
// board.Person is BoardPerson.
func (g *generator) name() error {
	g.prefix = map[string]string{}
	named := map[string][]*types.TypeName{}
	for _, obj := range g.found {
		named[obj.Name()] = append(named[obj.Name()], obj)
	}
	for _, objs := range named {
		if len(objs) < 2 {
			continue
		}
		for _, obj := range objs {
			if g.root == nil || obj.Pkg().Path() != g.root.Path() {
				g.prefix[obj.Pkg().Path()] = exported(obj.Pkg().Name())
			}
		}
	}
	is := map[string]*types.TypeName{}
	for _, q := range g.sorted() {
		obj := g.found[q]
		name := g.prefix[obj.Pkg().Path()] + obj.Name()
		if other, taken := is[name]; taken {
			return fmt.Errorf("%s and %s would both be %s in the app: rename one", qualified(other), q, name)
		}
		is[name] = obj
	}
	return nil
}

// sorted are the found types' qualified names, in order.
func (g *generator) sorted() []string {
	names := make([]string, 0, len(g.found))
	for q := range g.found {
		names = append(names, q)
	}
	slices.Sort(names)
	return names
}

// types is the TypeScript of the found types, as guts writes them.
//
// guts writes every exported type of a package it's told to generate, and
// of any other package only what those use. So a package with a type an
// endpoint is declared with is generated, without its types that weren't
// found, and the rest are only used.
func (g *generator) types() (string, error) {
	if len(g.found) == 0 {
		return "", nil
	}
	generate := map[string]*types.Package{}
	use := map[string]*types.Package{}
	for q, obj := range g.found {
		if g.starts[q] {
			generate[obj.Pkg().Path()] = obj.Pkg()
		}
	}
	for _, obj := range g.found {
		if generate[obj.Pkg().Path()] == nil {
			use[obj.Pkg().Path()] = obj.Pkg()
		}
	}

	gp, err := guts.NewGolangParser()
	if err != nil {
		return "", err
	}
	gp.PreserveComments()
	var skip []string
	for _, path := range paths(generate) {
		if err := gp.IncludeGenerateWithPrefix(path, g.prefix[path]); err != nil {
			return "", err
		}
		scope := generate[path].Scope()
		for _, n := range scope.Names() {
			if tn, ok := scope.Lookup(n).(*types.TypeName); ok && tn.Exported() && g.found[qualified(tn)] == nil {
				skip = append(skip, qualified(tn))
			}
		}
	}
	for _, path := range paths(use) {
		if err := gp.IncludeReference(path, g.prefix[path]); err != nil {
			return "", err
		}
	}
	if err := gp.ExcludeCustom(skip...); err != nil {
		return "", err
	}
	as := config.StandardMappings()
	for q, ts := range written {
		if _, ok := as[q]; !ok && ts == "unknown" {
			as[q] = config.OverrideLiteral(bindings.KeywordUnknown)
		}
	}
	for q, ts := range g.text {
		keyword := bindings.KeywordUnknown
		if ts == "string" {
			keyword = bindings.KeywordString
		}
		as[q] = config.OverrideLiteral(keyword)
	}
	gp.IncludeCustomDeclaration(as)

	ts, err := gp.ToTypescript()
	if err != nil {
		return "", err
	}
	usedEnums(gp, ts)
	ts.ApplyMutations(
		config.ExportTypes,
		enumsAsTypes,
		// A field that's left out when empty is optional, not null.
		config.SimplifyOptional,
		// Go sends null for a nil map, or a nil slice, in a struct. The
		// types say they're there: the plugin fills them, or marks them
		// omitempty.
		config.NotNullMaps,
		config.NullUnionSlices,
	)
	var missing []string
	out, err := ts.SerializeInOrder(func(nodes map[string]bindings.Node) []bindings.Node {
		var keep []bindings.Node
		var names []string
		for _, q := range g.sorted() {
			obj := g.found[q]
			names = append(names, g.prefix[obj.Pkg().Path()]+obj.Name())
		}
		slices.Sort(names)
		for _, name := range names {
			node, ok := nodes[name]
			if !ok {
				missing = append(missing, name)
				continue
			}
			keep = append(keep, node)
		}
		return keep
	})
	if err != nil {
		return "", err
	}
	if len(missing) > 0 {
		return "", fmt.Errorf("guts wrote nothing for %s", strings.Join(missing, ", "))
	}
	return strings.TrimPrefix(out, "// Code generated by 'guts'. DO NOT EDIT.\n\n"), nil
}

// enumsAsTypes writes a named string type with constants as the union of
// them, as guts's config.EnumAsTypes does, and keeps what's said above
// the type, which that drops.
func enumsAsTypes(ts *guts.Typescript) {
	ts.ForEach(func(key string, node bindings.Node) {
		enum, ok := node.(*bindings.Enum)
		if !ok {
			return
		}
		members := slices.Clone(enum.Members)
		slices.SortStableFunc(members, func(a, b *bindings.EnumMember) int {
			return strings.Compare(fmt.Sprint(literal(a.Value)), fmt.Sprint(literal(b.Value)))
		})
		union := &bindings.UnionType{}
		for _, m := range members {
			union.Types = append(union.Types, m.Value)
		}
		ts.ReplaceNode(key, &bindings.Alias{
			Name:            enum.Name,
			Modifiers:       enum.Modifiers,
			Type:            union,
			SupportComments: enum.SupportComments,
			Source:          enum.Source,
		})
	})
}

// literal is the value a member of an enum is, to put them in order.
func literal(v bindings.ExpressionType) any {
	if l, ok := v.(*bindings.LiteralType); ok {
		return l.Value
	}
	return ""
}

func paths(pkgs map[string]*types.Package) []string {
	var out []string
	for path := range pkgs {
		out = append(out, path)
	}
	slices.Sort(out)
	return out
}

// usedEnums makes a named string type of a package that's only used (such
// as board.Category) the union of its constants. guts brings only the
// types from those packages, not the constants beside them, so without
// this the type would be plain string.
func usedEnums(g *guts.GoParser, ts *guts.Typescript) {
	for path, pkg := range g.Pkgs {
		if !g.Reference[path] {
			continue
		}
		values := map[*types.TypeName][]string{}
		scope := pkg.Types.Scope()
		for _, name := range scope.Names() {
			c, ok := scope.Lookup(name).(*types.Const)
			if !ok || c.Val().Kind() != constant.String {
				continue
			}
			if named, ok := c.Type().(*types.Named); ok && named.Obj().Pkg() == pkg.Types {
				values[named.Obj()] = append(values[named.Obj()], constant.StringVal(c.Val()))
			}
		}
		for tn, vs := range values {
			key := g.Identifier(tn).Ref()
			node, ok := ts.Node(key)
			if !ok {
				continue // not used by a type that's written
			}
			alias, ok := node.(*bindings.Alias)
			if !ok {
				continue
			}
			slices.Sort(vs)
			union := &bindings.UnionType{}
			for _, v := range slices.Compact(vs) {
				union.Types = append(union.Types, &bindings.LiteralType{Value: v})
			}
			alias.Type = union
			ts.ReplaceNode(key, alias)
		}
	}
}

// ts is a type as Api writes it: what an endpoint is declared with.
func (g *generator) ts(t types.Type) string {
	switch t := types.Unalias(t).(type) {
	case *types.Named:
		obj := t.Origin().Obj()
		if obj.Pkg() == nil {
			if obj.Name() == "error" {
				return "string"
			}
			return "unknown"
		}
		q := qualified(obj)
		if as, ok := written[q]; ok {
			return as
		}
		if as, ok := g.text[q]; ok {
			return as
		}
		name := g.prefix[obj.Pkg().Path()] + obj.Name()
		if n := t.TypeArgs().Len(); n > 0 {
			args := make([]string, n)
			for i := range n {
				args[i] = g.ts(t.TypeArgs().At(i))
			}
			name += "<" + strings.Join(args, ", ") + ">"
		}
		return name
	case *types.Pointer:
		of := g.ts(t.Elem())
		if strings.HasSuffix(of, " | null") || of == "unknown" {
			return of
		}
		return of + " | null"
	case *types.Slice:
		return g.list(t.Elem())
	case *types.Array:
		return g.list(t.Elem())
	case *types.Map:
		key := "string"
		if b, ok := t.Key().Underlying().(*types.Basic); ok && b.Info()&types.IsNumeric != 0 {
			key = "number"
		}
		return "Record<" + key + ", " + g.ts(t.Elem()) + ">"
	case *types.Basic:
		switch {
		case t.Info()&types.IsBoolean != 0:
			return "boolean"
		case t.Info()&types.IsString != 0:
			return "string"
		case t.Info()&types.IsNumeric != 0:
			return "number"
		}
	}
	return "unknown"
}

// list is a slice or an array of elem. Bytes are sent as one string.
func (g *generator) list(elem types.Type) string {
	if b, ok := types.Unalias(elem).(*types.Basic); ok && b.Kind() == types.Byte {
		return "string"
	}
	of := g.ts(elem)
	if strings.Contains(of, " | ") {
		of = "(" + of + ")"
	}
	return of + "[]"
}

// wildcards are the names a path's values go by: key in
// /api/issues/{key}, and rest in /files/{rest...}.
func wildcards(path string) []string {
	var names []string
	for _, seg := range strings.Split(path, "/") {
		if !strings.HasPrefix(seg, "{") || !strings.HasSuffix(seg, "}") {
			continue
		}
		name := strings.TrimSuffix(seg[1:len(seg)-1], "...")
		if name == "" || name == "$" {
			continue
		}
		names = append(names, name)
	}
	return names
}
